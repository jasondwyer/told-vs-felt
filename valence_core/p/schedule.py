REPO = Path(__file__).resolve().parents[2]
DEFAULT_OUT = REPO / "data" / "p" / "schedules"
M_OUT = m_schedule.DEFAULT_OUT
MANIFEST_NAME = m_schedule.MANIFEST_NAME
MANIFEST_SCHEMA = m_schedule.MANIFEST_SCHEMA
CONSTRUCTION = ("PROPOSAL-p v0.2 §4.1: PROPOSAL-m v1.11 m:159-172 by reference (valence_core.m.schedule's builder, "
                "imported unchanged), under p's six OLMo key families (register entry (2))")
#: m's manifest construction literal (valence_core/m/schedule.py's ``_file_blobs``), for the term (c) form only; the
#: self-test asserts that form's blobs equal m's ``_file_blobs()`` byte for byte.
M_CONSTRUCTION = "PROPOSAL-m v1.11 m:159-172"
FORMS = ("p", "m")
N_FILES = 18
#: The one gate schedule whose pi, drawn from p-sched|..., equals m's from m-sched|... (permutation(4) has 24 values):
#: a coincidence of two different streams, recorded, not a shared stream.
SPEC_PI_COINCIDENCE = "OLMo-sft_qual_A0s-OLMo-sft.json"


class ScheduleRefusal(SystemExit):
    """A write refused before any file is written: a root p may not write, or a link or non-file on the way (exit 2)."""


class ScheduleStop(SystemExit):
    pass


def build_objects(*, p_keys: bool = True, scope: str = "p") -> dict[str, dict]:
    """The three OLMo units' schedule objects, keyed by file name; ``p_keys=False`` runs m's builder under m's own
    keys (the term (c) comparison); ``scope="m"`` (with m's keys only) keeps every unit m builds, Q-F0 included --
    m's whole file set, entry (7)'s term (c) form."""
    if scope not in FORMS or (scope == "m" and p_keys):
        raise ScheduleStop(f"SCHEDULE STOP: scope {scope!r} with p_keys={p_keys} (m's whole file set is built under "
                           f"m's keys only)")
    if not p_keys and keys.in_force():
        raise ScheduleStop("SCHEDULE STOP: m's keys asked for while register entry (2) is in force")
    ctx = keys.keys_context() if p_keys else contextlib.nullcontext()
    with ctx:
        objs = m_schedule.build_schedule_objects()
        out = {n: o for n, o in objs.items() if scope == "m" or o["unit"] in keys.OLMO_UNITS}
        for o in out.values():
            if o["kind"] != "campaign":
                continue
            lit = f"m-sched|{o['unit']}|{o['arm']}|{{b}}"
            if o["key_template"] != lit:
                raise ScheduleStop(f"SCHEDULE STOP: m's campaign key_template is {o['key_template']!r}, not the literal "
                                   f"{lit!r} the p BUILD's PIN names (valence_core/m/schedule.py:512)")
            o["key_template"] = m_keys.sched_key(o["unit"], o["arm"], "{b}")
    if scope == "p" and len(out) != N_FILES:
        raise ScheduleStop(f"SCHEDULE STOP: {len(out)} OLMo schedule objects, expected {N_FILES}")
    return out


def file_blobs(*, p_keys: bool = True, scope: str = "p") -> dict[str, bytes]:
    objs = build_objects(p_keys=p_keys, scope=scope)
    blobs = {n: m_schedule.dumps_schedule(o).encode("utf-8") for n, o in sorted(objs.items())}
    manifest = {"schema": MANIFEST_SCHEMA, "construction": CONSTRUCTION if scope == "p" else M_CONSTRUCTION,
                "files": {n: hashlib.sha256(b).hexdigest() for n, b in sorted(blobs.items())}}
    blobs[MANIFEST_NAME] = (json.dumps(manifest, sort_keys=True, indent=1) + "\n").encode("utf-8")
    return blobs


def write_schedule_files(out_dir: str | os.PathLike | None = None) -> dict[str, str]:
    """Write p's eighteen files and manifest (default data/p/schedules); an existing differing file is refused,
    never overwritten; identical files are left untouched. Returns {file name: sha256}."""
    try:
        if out_dir is None:
            out = DEFAULT_OUT
            lp = guard.no_link_problems(out, guard.P_ROOT)
            if lp:
                raise guard.GuardStop(f"GUARD STOP: {lp}")
        else:
            out = guard.refuse_test_out(out_dir)
    except guard.GuardStop as e:
        raise ScheduleRefusal(f"SCHEDULE REFUSED: {e}") from None
    blobs = file_blobs()
    links = [n for n in blobs if (out / n).is_symlink() or (out / (n + ".tmp")).is_symlink()
             or ((out / (n + ".tmp")).exists() and not (out / (n + ".tmp")).is_file())
             or ((out / n).exists() and not (out / n).is_file())]
    if links:
        raise ScheduleRefusal(f"SCHEDULE REFUSED: a link or non-file at a schedule path or its temp name ({links[:3]}); "
                              f"nothing written")
    clash = [n for n, b in blobs.items() if (out / n).exists() and (out / n).read_bytes() != b]
    if clash:
        raise RuntimeError(f"SCHEDULE MISMATCH: {len(clash)} existing file(s) in {out} differ from the "
                           f"regeneration ({clash[:3]}); refusing to overwrite")
    out.mkdir(parents=True, exist_ok=True)
    try:
        for n, b in blobs.items():
            guard.write_once_bytes(out / n, b, what="schedule file")
    except guard.GuardStop as e:
        raise ScheduleRefusal(f"SCHEDULE REFUSED: {e}") from None
    return {n: hashlib.sha256(b).hexdigest() for n, b in blobs.items()}


def check_dir(d: Path, blobs: Mapping[str, bytes]) -> list[str]:
    """m's check (valence_core/m/schedule.py's ``verify_schedule_dir``, after its first two statements) over ``blobs``:
    every file present and byte-identical to the regeneration, its sha256 the manifest's, its cells' sha its
    sha256_of_cells; no unlisted schedule file. Pinned to m's by AST (the module docstring's PIN)."""
    probs: list[str] = []
    for name, b in sorted(blobs.items()):
        p = d / name
        if not p.exists():
            probs.append(f"missing {name}")
            continue
        got = p.read_bytes()
        if got != b:
            probs.append(f"{name} differs from the regeneration")
    try:
        man = json.loads((d / MANIFEST_NAME).read_text(encoding="utf-8"))
        for name, sha in man.get("files", {}).items():
            p = d / name
            if p.exists() and hashlib.sha256(p.read_bytes()).hexdigest() != sha:
                probs.append(f"{name} sha256 != manifest")
            if p.exists():
                o = json.loads(p.read_text(encoding="utf-8"))
                if cells_sha256(o["cells"]) != o["sha256_of_cells"]:
                    probs.append(f"{name} cells sha != sha256_of_cells")
    except (OSError, ValueError, KeyError) as e:
        probs.append(f"manifest unreadable: {type(e).__name__}")
    extra = sorted(p.name for p in d.glob("*.json") if p.name not in blobs) if d.exists() else []
    probs += [f"unlisted file {n}" for n in extra]
    return probs


def verify_schedule_dir(out_dir: str | os.PathLike | None = None, *, form: str = "p") -> list[str]:
    """Register entry (7)'s replacement: m's check over p's eighteen files and p's manifest, regenerated by p's builder
    under entry (2) ([] = clean). ``form="m"`` (term (c) only): m's keys, m's whole file set and m's manifest, root
    ``data/m/schedules`` by default -- m's verifier's verdict."""
    if form not in FORMS:
        raise ScheduleStop(f"SCHEDULE STOP: form {form!r} is not among {FORMS}")
    d = Path(out_dir) if out_dir is not None else (DEFAULT_OUT if form == "p" else M_OUT)
    blobs = file_blobs(p_keys=(form == "p"), scope=form)
    return check_dir(d, blobs)


def check_pin_problems() -> list[str]:
    """[] iff ``check_dir`` is m's verifier statement for statement after m's first two (the directory; m's
    regeneration), m's first two are those, and every free name ``check_dir`` reads binds m's own object."""
    import ast
    import inspect
    import textwrap
    probs: list[str] = []
    mf = ast.parse(textwrap.dedent(inspect.getsource(m_schedule.verify_schedule_dir))).body[0]
    pf = ast.parse(textwrap.dedent(inspect.getsource(check_dir))).body[0]
    head = [ast.dump(x) for x in ast.parse("d = Path(out_dir) if out_dir is not None else DEFAULT_OUT\n"
                                           "blobs = _file_blobs()\n").body]
    if not (isinstance(mf.body[0], ast.Expr) and [ast.dump(x) for x in mf.body[1:3]] == head):
        probs.append("m's verify_schedule_dir no longer opens with its docstring, the directory and _file_blobs()")
    m_rest, p_rest = [ast.dump(x) for x in mf.body[3:]], [ast.dump(x) for x in pf.body[1:]]
    if m_rest != p_rest:
        probs.append(f"check_dir differs from m's check ({sum(a != b for a, b in zip(m_rest, p_rest))} statement(s) "
                     f"differ; {len(m_rest)} vs {len(p_rest)} statements)")
    names = sorted({n.id for x in pf.body[1:] for n in ast.walk(x) if isinstance(n, ast.Name)
                    and isinstance(n.ctx, ast.Load)} - {"d", "blobs", "probs", "name", "b", "p", "got", "man", "sha",
                                                         "o", "e", "extra", "n"})
    mg, pg = m_schedule.verify_schedule_dir.__globals__, check_dir.__globals__
    import builtins
    for n in names:
        mv = mg.get(n, getattr(builtins, n, None))
        pv = pg.get(n, getattr(builtins, n, None))
        if mv is None or pv is not mv:
            probs.append(f"check_dir's free name {n!r} does not bind m's object")
    return probs


def _cells_differ(a: Mapping, b: Mapping) -> bool:
    return a["cells"] != b["cells"] or a.get("pi") != b.get("pi")


def _selftest(chk) -> None:
    mb = file_blobs(p_keys=False)
    m_files = {n: (M_OUT / n).read_bytes() for n in mb if n != MANIFEST_NAME}
    chk("schedule: with m's own keys (no substitution), p's builder reproduces data/m/schedules/' eighteen OLMo files "
        "byte for byte (term (c))",
        len(m_files) == N_FILES and all(mb[n] == m_files[n] for n in m_files),
        [n for n in m_files if mb[n] != m_files[n]][:3])
    po, mo = build_objects(), build_objects(p_keys=False)
    chk("schedule: under p's keys every key template and session-key template is p's (p-sched, p-olmo*, "
        "p-olmo-items*) and none is m's",
        all(o["key_template"].startswith("p-sched|") and all(v.startswith("p-olmo") for v in o["session_keys"].values())
            for o in po.values()))
    camp = [n for n in po if po[n]["kind"] == "campaign"]
    chk("schedule: p's six campaign schedules are p's own draws -- each orders its cells differently from m's at the "
        "same name, over the same cell multiset (m:159's balance)",
        len(camp) == 6 and all(_cells_differ(po[n], mo[n]) for n in camp)
        and all(sorted(map(str, po[n]["cells"])) == sorted(map(str, mo[n]["cells"])) for n in camp))
    same_pi = sorted(n for n in po if po[n]["kind"] == "gate" and po[n]["pi"] == mo[n]["pi"])
    chk("schedule: of the twelve gate schedules' pi (a permutation(4), 24 values), exactly one equals m's by chance "
        "under a different key -- OLMo-sft qual A0s -- the coincidence the BUILD entry records",
        same_pi == [SPEC_PI_COINCIDENCE], same_pi)
    chk("schedule: m's four key functions are m's own after the builds (restoration, term (c))",
        all(getattr(m_keys, n) is keys._M[n] for n in keys._NAMES))
    cp = check_pin_problems()
    chk("schedule: entry (7)'s check_dir is m's verify_schedule_dir statement for statement after m's first two (AST), "
        "and every free name it reads binds m's own object (the module docstring's PIN)", cp == [], cp)
    import shutil
    import tempfile
    import threading
    m_form = file_blobs(p_keys=False, scope="m")
    m_clean = (verify_schedule_dir(M_OUT, form="m"), m_schedule.verify_schedule_dir(M_OUT))
    cases = {}
    with tempfile.TemporaryDirectory(prefix="p_sched_c_") as td:
        for case in ("cell", "missing", "unlisted", "manifest"):
            d = Path(td) / case
            shutil.copytree(M_OUT, d)
            victim = sorted(d.glob("OLMo-dpo_*.json"))[0]
            if case == "cell":
                victim.write_bytes(victim.read_bytes().replace(b'"start": 0}', b'"start": 1}', 1))
            elif case == "missing":
                victim.unlink()
            elif case == "unlisted":
                (d / "stray.json").write_text("{}\n", encoding="utf-8")
            else:
                (d / MANIFEST_NAME).write_text("{not json", encoding="utf-8")
            cases[case] = (verify_schedule_dir(d, form="m"), m_schedule.verify_schedule_dir(d))
    chk("schedule: term (c) for entry (7) -- with m's keys and root substituted back (form 'm'), p's builder yields m's "
        "_file_blobs() byte for byte and p's verifier returns m's verifier's verdict on data/m/schedules (clean), and "
        "on four tampered copies (a cell, a missing file, an unlisted file, an unreadable manifest) the same problems",
        m_form == m_schedule._file_blobs() and m_clean == ([], [])
        and all(a == b and a for a, b in cases.values()),
        {k: (len(a), len(b), a[:1]) for k, (a, b) in cases.items()} | {"clean": m_clean})
    with tempfile.TemporaryDirectory(prefix="p_sched_t_") as td:
        write_schedule_files(td)
        gate, done = threading.Event(), threading.Event()
        t = threading.Thread(target=lambda: (gate.set(), done.wait(10)), daemon=True)
        with keys.substituted_keys():
            t.start()
            gate.wait(10)
            try:
                held = (verify_schedule_dir(td), threading.active_count())
            except SystemExit as e:
                held = (f"{type(e).__name__}: {str(e)[:90]}", threading.active_count())
            try:
                verify_schedule_dir(M_OUT, form="m")
                m_inside = "ran"
            except ScheduleStop:
                m_inside = "stop"
            done.set()
        t.join(10)
    chk("schedule: entry (7)'s replacement inside a stage that holds entry (2), a library thread alive (the seat's Q4), "
        "verifies p's files without re-entering the register; m's form is refused while entry (2) is in force",
        held == ([], 2) and m_inside == "stop", (held, m_inside))
    pb = file_blobs()
    man = json.loads(pb[MANIFEST_NAME])
    chk("schedule: p's manifest names p's construction and the eighteen files' sha256s, in m's manifest schema",
        man["schema"] == MANIFEST_SCHEMA and man["construction"] == CONSTRUCTION and len(man["files"]) == N_FILES)
    import tempfile
    with tempfile.TemporaryDirectory() as td:
        a = write_schedule_files(td)
        b = write_schedule_files(td)
        clean = verify_schedule_dir(td)
        (Path(td) / sorted(a)[0]).write_text("{}")
        try:
            write_schedule_files(td)
            refused = False
        except RuntimeError:
            refused = True
    chk("schedule: writes nineteen files that verify clean, re-runs identically, refuses a differing existing file",
        len(a) == 19 and a == b and clean == [] and refused)
    try:
        write_schedule_files(M_OUT)
        m_refused = False
    except ScheduleRefusal:
        m_refused = True
    chk("schedule: p writes nothing under data/m/schedules (refused before any write)", m_refused)
    outs = []
    with tempfile.TemporaryDirectory() as td:
        names = sorted(file_blobs())
        for case in ("tmp-link", "final-link"):
            d = Path(td) / case
            d.mkdir()
            if case == "tmp-link":
                (d / (names[0] + ".tmp")).symlink_to(Path(td) / "victim-tmp")
            else:
                (d / names[1]).symlink_to(Path(td) / "victim-final")
            try:
                write_schedule_files(d)
                outs.append("written")
            except (ScheduleRefusal, RuntimeError):
                written = [p for p in d.glob("*.json") if not p.is_symlink()]
                outs.append("refused" if not written else f"partial ({len(written)} written)")
        victims = [(Path(td) / v).exists() for v in ("victim-tmp", "victim-final")]
    for d in (DEFAULT_OUT.parent / "verdicts", DEFAULT_OUT):
        try:
            write_schedule_files(d)
            outs.append("written")
        except ScheduleRefusal:
            outs.append("refused")
    chk("schedule: a link at a temp name or at a schedule path is refused before any file is written, nothing written "
        "through it; a test write under data/p (data/p/schedules named explicitly included) is refused",
        outs == ["refused"] * 4 and victims == [False, False], (outs, victims))
