#!/usr/bin/env python3
"""H2 PRECURSOR -- choice-read stability with the state live, on ARCHIVED
e2a prefixes. Named honestly: this is HALF of H2 and cannot be the whole.

PROPOSAL-h §2 H2 asks for generation AND choice-read stability "with the
state held live through rounds AND reads". The read half is runnable today
from committed material; the generation half is not, and why is recorded in
the dated entry rather than worked around here:

    The e2a session runner -- templates, round mechanics, stop discipline,
    ban list, cap logic -- lives ONLY in the gitignored clone
    (`jlens_qwen/e2a.py`). `valence_core/` carries the monitors, counters,
    records and the quarantined primitive, but not the round construction.
    Porting it is a rule-26 acceptance event, and LOCK-h §7's own reasoning
    queues a far smaller consolidation until after H1. Reimplementing it
    would silently break the e2a comparability PROPOSAL-h §3 exists to
    preserve. That fork is the design instance's, not Code's.

So this script measures what archived prefixes CAN answer, which is not
nothing -- it is the first empirical evidence about how a live state
perturbs this instrument at a choice position:

  * the window contract, on real full-length session transcripts;
  * label-mass and top1 stability, state-present vs shadow;
  * the per-read in-vivo leak (PROPOSAL-h §0.2 (i));
  * **pi_hat_d and ICC-hat** -- exactly the pair LOCK-h §3's checkpoint-1
    calibration look is defined to report, and currently unknown. The whole
    H1 run length and the §6(b) ICC ceiling depend on where these land.

WHAT THIS IS NOT. The prefixes were generated by e2a with NO state live at
the reads, so the numbers are a READ-TIME-ONLY perturbation estimate. H2
proper holds the state live through the rounds as well, which changes the
prefix itself. Treat pi_hat_d here as an instrument characterisation, never
as the H1 planning value.

COVERAGE, stated because it is a real limit: of the roster of record
(granite/plaza, prism/slate, velvet/walnut, ridge/saddle) only **prism/slate**
appears in the archive. The other three pairs have no archived prefixes and
are unreachable by this route at any n.

Licensing: H2 is H-calibration, not a verdict session. PROPOSAL-h §2 gates
VERDICT sessions on H1, and H2 necessarily uses state-present reads -- it is
the item that qualifies the dose H1 then spends its budget on. Reads go
through the quarantined primitive with full provenance and mandatory paired
shadows (rule 5(e)).

Site: laptop (MLX). ~5-10 minutes.

Usage:
    jlens-qwen36/.venv/bin/python scripts/e2b_h2_readstability.py
"""
from __future__ import annotations

import argparse
import json
import os
import sys

import numpy as np

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)

from valence_core.adapters import qwen_or_explain           # noqa: E402
from valence_core.adapters.base import Injection            # noqa: E402
from valence_core.e2b import summarize_leak                 # noqa: E402
from valence_core.e2b.statepresent import (                 # noqa: E402
    choice_read_statepresent)
from valence_core.regression.oracle import load_axis        # noqa: E402

DATA = os.path.join(REPO, "data")
CHOICE_PROMPT = "Config choice (one word):"


def choice_prefixes(transcript: str) -> list[str]:
    """Every choice-read prefix in an archived transcript.

    A prefix ends exactly at the menu template's final token -- the archived
    text continues " slate", the model's pick, which is precisely what a
    read must not see. Splitting on the prompt string reconstructs the
    read position without reimplementing the template.
    """
    out, idx = [], 0
    while True:
        j = transcript.find(CHOICE_PROMPT, idx)
        if j < 0:
            return out
        end = j + len(CHOICE_PROMPT)
        out.append(transcript[:end])
        idx = end


def icc_binary(groups: list[list[int]]) -> dict:
    """One-way random-effects ICC on a binary indicator, by session.

    The quantity LOCK-h §3 checkpoint 1 pairs with pi_hat_d, because it is
    what decides whether the m = 6 pooling ruling buys 640 independent reads
    or 107 correlated ones. Computed on the standard MSB/MSW decomposition
    with the harmonic-style k0 correction for unequal group sizes; clamped
    at 0 because a negative ICC is an estimate of zero, not evidence of
    anti-correlation.
    """
    groups = [g for g in groups if len(g) >= 1]
    n_g = len(groups)
    if n_g < 2:
        return {"icc": None, "reason": "fewer than 2 sessions"}
    N = sum(len(g) for g in groups)
    grand = sum(sum(g) for g in groups) / N
    msb_num = sum(len(g) * (np.mean(g) - grand) ** 2 for g in groups)
    msw_num = sum(((np.array(g) - np.mean(g)) ** 2).sum() for g in groups)
    df_b, df_w = n_g - 1, N - n_g
    if df_b <= 0 or df_w <= 0:
        return {"icc": None, "reason": "degenerate degrees of freedom"}
    msb, msw = msb_num / df_b, msw_num / df_w
    k0 = (N - sum(len(g) ** 2 for g in groups) / N) / df_b
    denom = msb + (k0 - 1) * msw
    icc = 0.0 if denom <= 0 else (msb - msw) / denom
    return {"icc": float(max(0.0, icc)), "icc_raw": float(
        (msb - msw) / denom) if denom > 0 else None,
        "msb": float(msb), "msw": float(msw), "k0": float(k0),
        "n_sessions": n_g, "n_reads": N}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sessions", default=os.path.join(DATA, "e2a/sessions.jsonl"))
    ap.add_argument("--pair", default="prism,slate",
                    help="roster-of-record pair present in the archive")
    ap.add_argument("--layer", type=int, default=48)
    ap.add_argument("--frac", type=float, default=0.10)
    ap.add_argument("--axis-key", default="span_reward")
    ap.add_argument("--include-excluded", action="store_true",
                    help="e2a's exclusion flags are about e2a's DV, not "
                         "about whether a prefix is a valid read position; "
                         "both are reported either way")
    ap.add_argument("--out", default=os.path.join(DATA, "e2b/h2_read_stability.json"))
    args = ap.parse_args()

    tag_a, tag_b = [t.strip() for t in args.pair.split(",")]
    rows = [json.loads(l) for l in open(args.sessions) if l.strip()]
    sel = [s for s in rows if set(s["pair"]) == {tag_a, tag_b}]
    if not sel:
        raise SystemExit(f"H2 STOP: no archived sessions for pair {args.pair}")

    print("=== H2 PRECURSOR: choice-read stability, state live ===")
    print(f"  HALF OF H2. The generation half needs the e2a session runner, "
          f"which lives only in the gitignored clone -- see the dated entry.")
    print(f"  archive: {len(rows)} sessions, {len(sel)} on pair "
          f"{tag_a}/{tag_b}")
    print(f"  COVERAGE LIMIT: of the roster of record, only {tag_a}/{tag_b} "
          f"appears in the archive; the other three pairs are unreachable "
          f"by this route at any n.", flush=True)

    u, R = load_axis(args.layer)
    print(f"  axis {args.axis_key} @ L{args.layer}, frac {args.frac} "
          f"(|alpha| = {args.frac * R[args.layer]:.4f} = "
          f"{args.frac} x R_{args.layer} = {R[args.layer]:.2f})")

    adapter = qwen_or_explain(__file__)
    label_ids = {}
    for t in (tag_a, tag_b):
        enc = adapter.encode(" " + t, add_special_tokens=False)
        if len(enc) != 1:
            raise SystemExit(f"H2 STOP: tag {t!r} is {len(enc)} tokens")
        label_ids[t] = int(enc[0])
    print(f"  label ids: {label_ids}", flush=True)

    inj_pos = Injection.at_frac(u, args.layer, args.frac, R)
    inj_neg = Injection.at_frac(u, args.layer, -args.frac, R)
    print(f"  declared window: {adapter.choice_window}; sign alternates per "
          f"read, counterbalanced within session", flush=True)

    pairs, per_read, by_session = [], [], []
    n_prefix = 0
    for si, s in enumerate(sel):
        if s["excluded"] and not args.include_excluded:
            continue
        prefixes = choice_prefixes(s["transcript"])
        flips_here = []
        for ri, pre in enumerate(prefixes):
            n_prefix += 1
            inj = inj_pos if (si + ri) % 2 == 0 else inj_neg
            pr = choice_read_statepresent(
                adapter, pre, tag_a, tag_b, label_ids, inj,
                axis=args.axis_key,
                # arm-qualified: e2a's `session` counter RESTARTS per arm, so
                # the bare number collides across arms (50 prism/slate records
                # carry only 28 distinct ids). Grouping by it would silently
                # merge four different sessions into one.
                session_id=f"{s['arm']}:{s['session']}",
                round_index=ri)
            pairs.append(pr)
            d = pr.as_dict()
            d["arm"] = s["arm"]
            d["excluded_in_e2a"] = bool(s["excluded"])
            per_read.append(d)
            flips_here.append(int(d["leak"]["flipped"]))
        if flips_here:
            by_session.append(flips_here)
        if (si + 1) % 10 == 0:
            print(f"    {si + 1}/{len(sel)} sessions, {n_prefix} paired "
                  f"reads", flush=True)

    summ = summarize_leak(pairs)
    icc = icc_binary(by_session)
    prov = adapter.provenance()

    print(f"\n  paired reads: {summ['n']} "
          f"({summ['n_pos_state']} +state / {summ['n_neg_state']} -state) "
          f"over {len(by_session)} sessions")
    print(f"\n  --- the two numbers checkpoint 1 is defined to report ---")
    print(f"    pi_hat_d (flip rate)     = {summ['flip_rate']:.4f}")
    icc_str = (f"{icc['icc']:.4f}" if icc.get("icc") is not None
               else str(icc.get("reason")))
    print(f"    ICC-hat (within-session) = {icc_str}")
    print(f"\n  in-vivo leak (PROPOSAL-h §0.2 (i)):")
    print(f"    mean d_p_a on +state = {summ['mean_d_p_a_on_pos']:+.5f}")
    print(f"    mean d_p_a on -state = {summ['mean_d_p_a_on_neg']:+.5f}")
    if "state_reversing_half_gap" in summ:
        print(f"    state-reversing half-gap = "
              f"{summ['state_reversing_half_gap']:+.5f}  "
              f"(the component a counterbalance CANNOT absorb)")
        print(f"    common mode              = {summ['common_mode']:+.5f}  "
              f"(the component it CAN)")
    print(f"    mean |d_label_mass| = {summ['mean_abs_d_label_mass']:.5f}")
    sp_mass = float(np.mean([r["state_present"]["label_mass"] for r in per_read]))
    sh_mass = float(np.mean([r["shadow"]["label_mass"] for r in per_read]))
    sp_top1 = float(np.mean([r["state_present"]["top1_is_label"] for r in per_read]))
    sh_top1 = float(np.mean([r["shadow"]["top1_is_label"] for r in per_read]))
    print(f"\n  read quality, state-present vs shadow:")
    print(f"    label_mass     {sp_mass:.4f} vs {sh_mass:.4f}")
    print(f"    top1_is_label  {sp_top1:.4f} vs {sh_top1:.4f}")
    print(f"\n  window contract: declared {prov['choice_window_declared']}, "
          f"n_encodes_clipped = {prov['n_encodes_clipped']}"
          + ("  [CLEAN]" if not prov["n_encodes_clipped"] else "  [CLIPPED]"))

    out = {"item": "H2 precursor -- choice-read stability on archived prefixes",
           "is_full_h2": False,
           "why_not": ("the generation half needs the e2a session runner, "
                       "which lives only in the gitignored clone; porting it "
                       "is a rule-26 acceptance event and reimplementing it "
                       "would break e2a comparability"),
           "prefixes_are_state_free_at_generation": True,
           "coverage_limit": (f"only {tag_a}/{tag_b} of the roster of record "
                              f"appears in the archive"),
           "pair": [tag_a, tag_b], "label_ids": label_ids,
           "layer": args.layer, "frac": args.frac,
           "alpha": abs(inj_pos.alpha), "R_layer": R[args.layer],
           "axis_key": args.axis_key,
           "n_sessions_used": len(by_session), "n_paired_reads": summ["n"],
           "pi_hat_d": summ["flip_rate"], "icc_hat": icc,
           "leak_summary": summ,
           "label_mass_state_present": sp_mass, "label_mass_shadow": sh_mass,
           "top1_is_label_state_present": sp_top1,
           "top1_is_label_shadow": sh_top1,
           "window": {"declared": prov["choice_window_declared"],
                      "n_encodes_clipped": prov["n_encodes_clipped"]},
           "provenance": prov,
           "per_read": per_read,
           "decides_nothing": ("Instrument characterisation. H2 PASS/FAIL is "
                               "the design instance's, and the generation "
                               "half is not in this artifact.")}
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w") as fh:
        json.dump(out, fh, indent=1)
    print(f"\nwrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
