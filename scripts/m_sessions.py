def build_schedules(out: Path) -> int:
    from valence_core.m import schedule
    before = {p.name: p.read_bytes() for p in out.glob("*.json")} if out.exists() else {}
    try:
        shas = schedule.write_schedule_files(out)
    except RuntimeError as e:
        print(f"REFUSED: {e}", flush=True)
        return 1
    written = sorted(n for n in shas if before.get(n) != (out / n).read_bytes())
    total = sum((out / n).stat().st_size for n in shas)
    man = hashlib.sha256((out / schedule.MANIFEST_NAME).read_bytes()).hexdigest()
    print(f"SCHEDULES {out}: {len(shas)} files, {total} bytes, manifest sha256 {man}; "
          f"{len(written)} written, {len(shas) - len(written)} unchanged", flush=True)
    probs = schedule.verify_schedule_dir(out)
    print("VERIFY clean" if not probs else f"VERIFY PROBLEMS {probs}", flush=True)
    return 0 if not probs else 1


