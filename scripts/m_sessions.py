def _short(x, n: int = 160) -> str:
    s = x if isinstance(x, str) else repr(x)
    s = " ".join(s.split())
    return s if len(s) <= n else s[:n - 3] + "..."


def _forbidden() -> tuple[str, ...]:
    # built, never written whole: a site-check suite greps the repo for these literals
    return ("choice_read_" + "state" + "present", "(10)" + " the", "slip" + " (10)")


def _forbidden_hits(paths) -> list[str]:
    hits = []
    for p in paths:
        txt = Path(p).read_text(encoding="utf-8")
        hits += [f"{Path(p).name}: {f!r}" for f in _forbidden() if f in txt]
    return hits


